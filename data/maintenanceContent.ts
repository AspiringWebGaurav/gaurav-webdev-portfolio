export function getRandomTitle(phase: 'onTrack' | 'slightlyOver' | 'extended' | 'longSession'): string {
  const titles = TITLES[phase];
  return titles[Math.floor(Math.random() * titles.length)];
}

export function getRandomFunFacts(count: number = 4): typeof FUN_FACTS {
  const shuffled = [...FUN_FACTS].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}

export function getRandomActivity(): string {
  return CURRENT_ACTIVITIES[Math.floor(Math.random() * CURRENT_ACTIVITIES.length)];
}

export function getPhaseFromOverdue(overdueMinutes: number, isOverdue: boolean): 'onTrack' | 'slightlyOver' | 'extended' | 'longSession' {
  if (!isOverdue) return 'onTrack';
  if (overdueMinutes <= 15) return 'slightlyOver';
  if (overdueMinutes <= 60) return 'extended';
  return 'longSession';
}

